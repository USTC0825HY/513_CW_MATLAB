    num2str(details.criticalInput.criticalCodePp, 15); ...
    num2str(details.criticalInput.criticalInputVpp, 15); ...
    num2str(details.criticalInput.criticalInputDbm, 15); ...
    char(details.criticalInput.limitingRail); ...
    num2str(details.criticalInput.lastUnclippedInputVpp, 15); ...
    num2str(details.criticalInput.firstClippedInputVpp, 15); ...
    num2str(details.criticalInput.extrapolationRatio, 15); ...
    num2str(details.criticalInput.positiveRailFitR2, 15); ...
    num2str(details.criticalInput.negativeRailFitR2, 15)};
