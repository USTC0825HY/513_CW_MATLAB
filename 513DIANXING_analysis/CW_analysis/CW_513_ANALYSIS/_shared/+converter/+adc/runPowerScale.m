    'VariableNames', {'CalibrationItem', 'Value'});
end

function criticalTable = createCriticalInputTable(details)
%CREATECRITICALINPUTTABLE Export one traceable critical-input estimate.

critical = details.criticalInput;
criticalTable = table(string(details.channelName), critical.available, ...
    critical.status, critical.reason, critical.method, ...
    critical.thresholdFraction, critical.thresholdPeakCode, ...
    critical.criticalCodePp, critical.criticalInputVpp, ...
    critical.criticalInputDbm, critical.limitingRail, ...
    critical.positiveRailCriticalVpp, critical.negativeRailCriticalVpp, ...
    critical.positiveRailFitR2, critical.negativeRailFitR2, ...
    critical.lastUnclippedInputVpp, critical.firstClippedInputVpp, ...
    critical.lastUnclippedInputDbm, critical.firstClippedInputDbm, ...
    critical.extrapolationRatio, critical.bracketed, ...
    'VariableNames', {'Channel', 'Available', 'Status', 'Reason', 'Method', ...
    'ThresholdFraction', 'ThresholdPeakCode', 'CriticalCodePp', ...
    'CriticalInputVpp', 'CriticalInputDbm', 'LimitingRail', ...
    'PositiveRailCriticalVpp', 'NegativeRailCriticalVpp', ...
    'PositiveRailFitR2', 'NegativeRailFitR2', ...
    'LastUnclippedInputVpp', 'FirstClippedInputVpp', ...
    'LastUnclippedInputDbm', 'FirstClippedInputDbm', ...
    'ExtrapolationRatio', 'Bracketed'});
end

function printCriticalInput(critical)
%PRINTCRITICALINPUT Print the estimate without promoting it to a verdict.

if ~critical.available
    fprintf('99%% 临界输入估计不可用：%s\n', char(critical.reason));
    return;
end
if isfinite(critical.criticalInputDbm)
    fprintf('99%% 临界输入估计：%.9g Vpp / %+.6g dBm（%s，%s）\n', ...
        critical.criticalInputVpp, critical.criticalInputDbm, ...
        char(critical.limitingRail), char(critical.status));
else
    fprintf('99%% 临界输入估计：%.9g Vpp（%s，%s）\n', ...
        critical.criticalInputVpp, char(critical.limitingRail), ...
        char(critical.status));
end
end

function impedance = getReferenceImpedance(config)
%GETREFERENCEIMPEDANCE Resolve the explicit Vpp reference resistance.

if isfield(config, 'referenceImpedanceOhm') && ...
        ~isempty(config.referenceImpedanceOhm)
    impedance = config.referenceImpedanceOhm;
else
    impedance = 50;
end
if ~isscalar(impedance) || (~isnan(impedance) && ...
        (~isfinite(impedance) || impedance <= 0))
    error('converter:adc:InvalidReferenceImpedance', ...
        'referenceImpedanceOhm 必须为正的有限标量。');
end
end

function value = getConfigText(config, fieldName)
if isfield(config, fieldName) && ~isempty(config.(fieldName))
    value = char(config.(fieldName));
else
    value = 'unknown';
end
end
