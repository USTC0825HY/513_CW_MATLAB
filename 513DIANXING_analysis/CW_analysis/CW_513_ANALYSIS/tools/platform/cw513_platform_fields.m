function fields = cw513_platform_fields(config,entry)
%CW513_PLATFORM_FIELDS Describe source defaults without duplicating values.
fields = {};
locked = {'deviceId','analysisId','version','releaseReady','dataFolder', ...
    'outputFolder','outputRoot','inputFiles','entries','selectedFiles', ...
    'pairManifest','showFigures','allowRadixPrompt','parameterSources', ...
    'headerModulePattern','moduleChannelMap','jgChannelNumbers','jgChannelNames', ...
    'channelNames','adcFullScalePeakCode','sampleRateSource','sampleRateDefinition', ...
    'adcCodingDefinition','codeConversionRule','calibrationSource','formalLimitation', ...
    'requirementSourceDocument','requirementSourceSha256','requirementAsdId', ...
    'requirementIntegratedId','formalConditionSource','boardSeriesROhm','sourceROhm'};
picoAllowed = {'fpgaGain','asdCheckHz','referencePlane','plotDpi','welch','waveVariable','metadata'};
names = fieldnames(config);
for k = 1:numel(names)
    name = names{k};
    value = config.(name);
    editable = ~ismember(name,locked);
    if strcmp(entry.metric,'pico_noise'), editable = ismember(name,picoAllowed); end
    if strcmp(entry.invocation,'hex766'), editable = false; end
    if strcmp(entry.input_kind,'mat') && strcmp(name,'sampleRate'), editable = false; end
    item = struct('name',name,'label',localLabel(name),'unit',localUnit(name), ...
        'type',localType(value),'editable',editable,'value',value,'nonfinite','', ...
        'source','device private configuration');
    if strcmp(entry.input_kind,'mat') && strcmp(name,'sampleRate')
        item.label = '配置参考采样率（实测值读取MAT时基）';
    end
    if isnumeric(value) && isscalar(value) && ~isfinite(value)
        item.nonfinite = num2str(value);
    end
    fields{end+1} = item; %#ok<AGROW>
end
end

