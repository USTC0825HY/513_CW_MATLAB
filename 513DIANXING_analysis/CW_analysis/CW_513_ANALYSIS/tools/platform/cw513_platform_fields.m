end

function unit = localUnit(name)
unit = '';
if contains(lower(name),'hz') || ismember(name,{'sampleRate','targetResolutionHz'})
    unit = 'Hz';
elseif contains(lower(name),'dbm'), unit = 'dBm';
elseif contains(lower(name),'ohm'), unit = 'ohm';
elseif ismember(name,{'powerRangeVpp','edgeThreshold','levelTolV'}), unit = 'V';
elseif strcmp(name,'minHoldS'), unit = 's';
elseif contains(lower(name),'bits'), unit = 'bit';
end
end

function kind = localType(value)
if islogical(value), kind = 'boolean';
elseif isnumeric(value) && isscalar(value), kind = 'number';
elseif ischar(value) || (isstring(value) && isscalar(value)), kind = 'string';
elseif isstruct(value), kind = 'object';
else, kind = 'array';
end
end
