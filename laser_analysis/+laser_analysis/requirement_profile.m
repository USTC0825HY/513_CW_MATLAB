function requirements = requirement_profile(board, profile)
%REQUIREMENT_PROFILE Return versioned electrical-test requirements.
%   REQUIREMENTS = laser_analysis.requirement_profile(BOARD, PROFILE)
%   returns a table for "digital_lock" or "delay_driver" and "CW" or "GS".
%   CW contains reviewed values transcribed from the two 2026-07 public
%   test specifications. Conflicting source values remain separate rows
%   with state="conflict"; callers must not select one silently.
%
%   Numeric limits use SI-compatible units stated in the unit column.
%   A row with state other than "approved" cannot produce a formal pass or
%   fail judgment.

arguments
    board (1, 1) string
    profile (1, 1) string
end

board = lower(strtrim(board));
profile = upper(strtrim(profile));
if ~ismember(board, ["digital_lock", "delay_driver"])
    error('laser_analysis:UnknownBoard', ...
        'board must be digital_lock or delay_driver.');
end
if ~ismember(profile, ["CW", "GS"])
    error('laser_analysis:UnknownProfile', 'profile must be CW or GS.');
end

source = localSource(board);
if profile == "GS"
    requirements = localGsPlaceholder(board, profile, source);
    return;
end

if board == "digital_lock"
    requirements = localDigitalLockCw(source);
else
    requirements = localDelayDriverCw(source);
end
end

function source = localSource(board)
%LOCALSource Return immutable source identity for a requirement profile.
if board == "digital_lock"
    source.document = "光梳频率梳数字锁定板 测试细则（公开）.docx";
    source.sha256 = ...
        "BCA172A43422FC965EB5131FDF7B221E57D77819EAC1BF19502CAE3D6355BF26";
else
    source.document = "光梳频率梳延迟驱动板 测试细则（公开）.docx";
    source.sha256 = ...
        "9C5FDDBDAAAB3EABA824C64523A61392B5220F16BDD6C21A6FBFC8DC1193B630";
end
end

