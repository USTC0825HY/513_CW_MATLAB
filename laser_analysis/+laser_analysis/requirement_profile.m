function out = localGsPlaceholder(board, profile, source)
%LOCALGSPLACEHOLDER Expose the GS schema without enabling formal judgment.
rows = {
    upper(board) + "-GS-PENDING", "all", "profile_review", "", ...
        NaN, NaN, "", "GS channel and interface map not yet reviewed", ...
        "3.2", "unreviewed", ...
        "Schema only; GS must not be used for formal compliance."
    };
out = localRowsToTable(rows, board, profile, source);
end

function out = localRowsToTable(rows, board, profile, source)
%LOCALROWSTOTABLE Convert row cells to the stable requirement table schema.
out = cell2table(rows, 'VariableNames', { ...
    'requirement_id', 'subsystem', 'metric', 'operator', ...
    'limit_a', 'limit_b', 'unit', 'test_condition', ...
    'source_section', 'state', 'conflict_note'});
out.requirement_id = string(out.requirement_id);
out.subsystem = string(out.subsystem);
out.metric = string(out.metric);
out.operator = string(out.operator);
out.unit = string(out.unit);
out.test_condition = string(out.test_condition);
out.source_section = string(out.source_section);
out.state = string(out.state);
out.conflict_note = string(out.conflict_note);
out.board = repmat(string(board), height(out), 1);
out.profile = repmat(string(profile), height(out), 1);
out.source_document = repmat(source.document, height(out), 1);
out.source_sha256 = repmat(source.sha256, height(out), 1);
out = movevars(out, {'board', 'profile'}, 'Before', 'requirement_id');
end
