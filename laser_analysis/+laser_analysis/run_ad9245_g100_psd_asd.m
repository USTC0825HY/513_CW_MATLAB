required = {'channel', 'dacChannel', 'variant', 'caseName', 'inputMat', ...
    'adcCalibrationCsv', 'dacCalibrationCsv', 'outputDir', ...
    'fpgaGain', 'fpgaGainEvidence', 'requirementBandEndHz', ...
    'extendedAnalysisEndHz', 'asdLimitAt1HzUvPerSqrtHz', ...
    'requirementTestCondition', 'welchWindowSeconds', 'overlapRatio', ...
    'windowSensitivitySeconds', 'lowFrequencyExportEndHz', ...
    'spurMinimumFrequencyHz', 'spurMinimumSeparationHz', 'spurCount', ...
    'plotDpi', 'useMatLength', 'scriptVersion'};
for k = 1:numel(required)
    if ~isfield(cfg, required{k})
        error('laser_analysis:MissingConfig', 'Missing cfg.%s.', required{k});
    end
end
end

function mask = bandMask(frequency, startHz, endHz, df)
tolerance = max(abs(df) * 1e-6, eps(max(abs(frequency))) * 10);
mask = frequency >= startHz - tolerance & frequency <= endHz + tolerance;
end

function out = makeBandSummary(f, pOut, pIn, names, starts, ends, df, adc, dac)
nBand = numel(names);
values = NaN(nBand, 13);
binCount = zeros(nBand, 1);
for k = 1:nBand
    mask = bandMask(f, starts(k), ends(k), df);
    fx = f(mask); po = pOut(mask); pi = pIn(mask);
    if isempty(fx), continue; end
    ao = sqrt(max(po, 0)) * 1e6; ai = sqrt(max(pi, 0)) * 1e9;
    binCount(k) = numel(fx);
    [outMax, outIndex] = max(ao); [inMax, inIndex] = max(ai);
    values(k, :) = [median(ao), mean(ao), percentile(ao, 95), outMax, ...
        fx(outIndex), integrateNoise(fx, po), median(ai), mean(ai), ...
        percentile(ai, 95), inMax, fx(inIndex), integrateNoise(fx, pi), df];
end
out = table(names, starts, ends, binCount, values(:, 1), values(:, 2), ...
    values(:, 3), values(:, 4), values(:, 5), values(:, 6), ...
    values(:, 7), values(:, 8), values(:, 9), values(:, 10), ...
    values(:, 11), values(:, 12), values(:, 13));
out.Properties.VariableNames = {'Band', 'Start_Hz', 'End_Hz', 'BinCount', ...
    sprintf('%s_Output_ASD_Median_uV_per_sqrtHz', dac), ...
    sprintf('%s_Output_ASD_Mean_uV_per_sqrtHz', dac), ...
    sprintf('%s_Output_ASD_P95_uV_per_sqrtHz', dac), ...
    sprintf('%s_Output_ASD_Max_uV_per_sqrtHz', dac), ...
    sprintf('%s_Output_ASD_Max_Frequency_Hz', dac), ...
    sprintf('%s_Output_IntegratedNoise_uVrms', dac), ...
    sprintf('%s_InputEq_ASD_Median_nV_per_sqrtHz', adc), ...
    sprintf('%s_InputEq_ASD_Mean_nV_per_sqrtHz', adc), ...
    sprintf('%s_InputEq_ASD_P95_nV_per_sqrtHz', adc), ...
    sprintf('%s_InputEq_ASD_Max_nV_per_sqrtHz', adc), ...
    sprintf('%s_InputEq_ASD_Max_Frequency_Hz', adc), ...
    sprintf('%s_InputEq_IntegratedNoise_uVrms', adc), ...
    'FrequencyResolution_Hz'};
end

function value = integrateNoise(f, p)
if numel(f) > 1, value = sqrt(trapz(f, p)) * 1e6; else, value = NaN; end
end

function value = percentile(data, pct)
sorted = sort(double(data(:)));
if isempty(sorted), value = NaN; return; end
position = 1 + (numel(sorted) - 1) * pct / 100;
lo = floor(position); hi = ceil(position);
if lo == hi, value = sorted(lo);
else, value = sorted(lo) * (hi - position) + sorted(hi) * (position - lo); end
end

function out = makeWindowSensitivity(x, fs, seconds, overlapRatio, scale, adc, dac)
nCase = numel(seconds);
df = NaN(nCase, 1); segments = NaN(nCase, 1); at1 = NaN(nCase, 1);
outAsd = NaN(nCase, 1); inAsd = NaN(nCase, 1);
inMedian = NaN(nCase, 1); inMax = NaN(nCase, 1);
for k = 1:nCase
    nw = min(round(seconds(k) * fs), numel(x));
    if nw < numel(x), no = floor(nw * overlapRatio); else, no = 0; end
    [p, f] = pwelch(x, hann(nw, 'periodic'), no, nw, fs, 'onesided');
    ao = sqrt(max(p, 0)); ai = ao * scale;
    [~, idx] = min(abs(f - 1)); df(k) = f(2) - f(1);
    mask = bandMask(f, 0.8, 1.2, df(k));
    segments(k) = 1 + floor((numel(x) - nw) / (nw - no));
    at1(k) = f(idx); outAsd(k) = ao(idx) * 1e6; inAsd(k) = ai(idx) * 1e9;
    inMedian(k) = median(ai(mask)) * 1e9; inMax(k) = max(ai(mask)) * 1e9;
end
out = table(seconds, df, segments, at1, outAsd, inAsd, inMedian, inMax);
out.Properties.VariableNames = {'Window_s', 'Df_Hz', 'SegmentCount', ...
    'FrequencyAt1Hz_Hz', sprintf('%s_Output_ASD_1Hz_uV_per_sqrtHz', dac), ...
    sprintf('%s_InputEq_ASD_1Hz_nV_per_sqrtHz', adc), ...
    sprintf('%s_InputEq_ASD_0p8_1p2Hz_Median_nV_per_sqrtHz', adc), ...
    sprintf('%s_InputEq_ASD_0p8_1p2Hz_Max_nV_per_sqrtHz', adc)};
end

function [out, inputNv] = makeSegmentStability(x, fs, window, nw, step, nfft, scale, adc, dac)
startSample = (1:step:(numel(x) - nw + 1)).';
startTime = (startSample - 1) / fs;
outputUv = NaN(numel(startSample), 1); inputNv = NaN(numel(startSample), 1);
for k = 1:numel(startSample)
    idx = startSample(k):(startSample(k) + nw - 1);
    segment = x(idx) - mean(x(idx));
    [p, f] = periodogram(segment, window, nfft, fs, 'onesided');
    [~, at1] = min(abs(f - 1));
    outputUv(k) = sqrt(p(at1)) * 1e6;
    inputNv(k) = sqrt(p(at1)) * scale * 1e9;
end
out = table(startSample, startTime, outputUv, inputNv);
out.Properties.VariableNames = {'StartSample', 'StartTime_s', ...
    sprintf('%s_Output_ASD_1Hz_uV_per_sqrtHz', dac), ...
    sprintf('%s_InputEq_ASD_1Hz_nV_per_sqrtHz', adc)};
end

function out = makeTopSpurs(f, p, scale, count, minF, maxF, separation, adc, dac)
candidate = find(f >= minF & f <= maxF & isfinite(p) & p > 0);
[~, order] = sort(p(candidate), 'descend'); candidate = candidate(order);
selected = zeros(count, 1); selectedCount = 0;
for k = 1:numel(candidate)
    idx = candidate(k);
    if selectedCount == 0 || all(abs(f(idx) - f(selected(1:selectedCount))) >= separation)
        selectedCount = selectedCount + 1; selected(selectedCount) = idx;
        if selectedCount == count, break; end
    end
end
selected = selected(1:selectedCount); rank = (1:selectedCount).';
frequencyHz = f(selected); outputPsd = p(selected); outputAsdUv = sqrt(outputPsd) * 1e6;
inputPsd = outputPsd * scale^2; inputAsdNv = sqrt(inputPsd) * 1e9;
out = table(rank, frequencyHz, outputPsd, outputAsdUv, inputPsd, inputAsdNv);
out.Properties.VariableNames = {'rank', 'frequency_Hz', ...
    sprintf('%s_Output_PSD_V2_per_Hz', dac), ...
    sprintf('%s_Output_ASD_uV_per_sqrtHz', dac), ...
    sprintf('%s_InputEq_PSD_V2_per_Hz', adc), ...
    sprintf('%s_InputEq_ASD_nV_per_sqrtHz', adc)};
end

function [out, manifest] = buildSourceManifest(cfg)
roles = ["noise MAT"; "ADC measured calibration summary"; ...
    "DAC measured calibration summary"];
paths = string({cfg.inputMat; cfg.adcCalibrationCsv; cfg.dacCalibrationCsv});
if isfield(cfg, 'auxiliaryEvidence') && exist(cfg.auxiliaryEvidence, 'file')
    roles(end + 1, 1) = string(cfg.auxiliaryEvidenceRole);
    paths(end + 1, 1) = string(cfg.auxiliaryEvidence);
end
if isfield(cfg, 'requirementSource') && exist(cfg.requirementSource, 'file')
    roles(end + 1, 1) = "requirement screenshot";
    paths(end + 1, 1) = string(cfg.requirementSource);
end
sizeBytes = zeros(numel(paths), 1); modified = strings(numel(paths), 1);
hashes = strings(numel(paths), 1);
for k = 1:numel(paths)
    info = dir(char(paths(k))); sizeBytes(k) = info.bytes;
    modified(k) = string(datetime(info.datenum, 'ConvertFrom', ...
        'datenum', 'Format', 'yyyy-MM-dd HH:mm:ss'));
    hashes(k) = sha256(char(paths(k)));
end
out = table(roles, paths, sizeBytes, modified, hashes, ...
    'VariableNames', {'sourceRole', 'sourcePath', 'sourceSizeBytes', ...
    'sourceModifiedTime', 'sourceSha256'});
manifest = strjoin(roles + "=" + hashes, ';');
end

