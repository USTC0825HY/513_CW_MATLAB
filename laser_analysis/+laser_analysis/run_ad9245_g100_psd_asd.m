function result = run_ad9245_g100_psd_asd(cfg)
%RUN_AD9245_G100_PSD_ASD Shared AD9245-FPGA-DAC G100 PSD/ASD runner.
%   RESULT contains the resolved configuration, source/calibration evidence,
%   spectra, summary tables, and every generated output path.  The result is
%   conditional on the configured FPGA gain and retains DAC/Pico background.
%   Override cfg.outputDir for smoke tests; no formal report is modified.

arguments
    cfg (1, 1) struct
end
cfg = validateConfig(cfg);
adc = string(cfg.channel);
dac = string(cfg.dacChannel);
prefix = string(cfg.caseName);

required = {cfg.inputMat, cfg.adcCalibrationCsv, cfg.dacCalibrationCsv};
for k = 1:numel(required)
    if ~exist(required{k}, 'file')
        error('laser_analysis:MissingSource', ...
            'Required source does not exist: %s', required{k});
    end
end
if ~exist(cfg.outputDir, 'dir'), mkdir(cfg.outputDir); end
if isfield(cfg, 'requirementSource') && exist(cfg.requirementSource, 'file')
    copyfile(cfg.requirementSource, ...
        fullfile(cfg.outputDir, 'ADC_noise_requirement_source.png'));
end

adcTable = readtable(cfg.adcCalibrationCsv);
adcMask = strcmp(string(adcTable.fitName), 'primary_non_near_rail');
if nnz(adcMask) ~= 1
    error('laser_analysis:CalibrationRow', ...
        'Expected exactly one primary %s calibration row.', adc);
end
kAdc = adcTable.slopeVPerCode(adcMask);
adcReferencePlane = string(adcTable.referencePlane(adcMask));
dacTable = readtable(cfg.dacCalibrationCsv);
if height(dacTable) ~= 1 || ~ismember('slope_vpp_per_code', dacTable.Properties.VariableNames)
    error('laser_analysis:CalibrationRow', ...
        'Expected one DAC summary row with slope_vpp_per_code.');
end
kDac = dacTable.slope_vpp_per_code(1);
if ~isfinite(kAdc) || ~isfinite(kDac) || kAdc <= 0 || kDac <= 0
    error('laser_analysis:CalibrationValue', 'Invalid ADC or DAC calibration slope.');
end
inputPerOutputScale = kAdc / (abs(cfg.fpgaGain) * kDac);

raw = load(cfg.inputMat);
if ~isfield(raw, 'A') || ~isfield(raw, 'Tinterval')
    error('laser_analysis:MatSchema', 'MAT must contain A and Tinterval.');
end
rawVector = double(raw.A(:));
rawVectorCount = numel(rawVector);
metadataLength = rawVectorCount;
if cfg.useMatLength && isfield(raw, 'Length') && ...
        ~isempty(raw.Length) && isfinite(double(raw.Length(1)))
    metadataLength = min(rawVectorCount, max(1, floor(double(raw.Length(1)))));
end
trailingSamplesExcluded = rawVectorCount - metadataLength;
outputVoltage = rawVector(1:metadataLength);
finiteMask = isfinite(outputVoltage);
nonfiniteSamplesExcluded = nnz(~finiteMask);
outputVoltage = outputVoltage(finiteMask);
dt = double(raw.Tinterval(1));
if ~isfinite(dt) || dt <= 0
    error('laser_analysis:MatSchema', 'Invalid Tinterval in source MAT.');
end
fs = 1 / dt;
n = numel(outputVoltage);
duration = n / fs;
nyquist = fs / 2;
if n < round(cfg.welchWindowSeconds * fs)
    error('laser_analysis:ShortRecord', ...
        'Record is shorter than the configured Welch window.');
end

outputMean = mean(outputVoltage);
outputZeroMean = outputVoltage - outputMean;
inputEquivalent = outputZeroMean * inputPerOutputScale;
rawMedian = median(outputVoltage);
rawMad = median(abs(outputVoltage - rawMedian));
robustSigma = 1.4826 * rawMad;
if robustSigma > 0
    outlier8SigmaCount = nnz(abs(outputVoltage - rawMedian) > 8 * robustSigma);
else
    outlier8SigmaCount = 0;
end
outlier8SigmaPercent = 100 * outlier8SigmaCount / n;

windowSamples = min(round(cfg.welchWindowSeconds * fs), n);
overlapSamples = floor(windowSamples * cfg.overlapRatio);
nfft = windowSamples;
window = hann(windowSamples, 'periodic');
[psdOutput, frequency] = pwelch(outputZeroMean, window, ...
    overlapSamples, nfft, fs, 'onesided');
asdOutput = sqrt(max(psdOutput, 0));
psdInput = psdOutput * inputPerOutputScale^2;
asdInput = sqrt(max(psdInput, 0));
df = frequency(2) - frequency(1);
step = windowSamples - overlapSamples;
segmentCount = 1 + floor((n - windowSamples) / step);

fullWindow = hann(n, 'periodic');
[psdFullOutput, frequencyFull] = periodogram( ...
    outputZeroMean, fullWindow, n, fs, 'onesided');
asdFullOutput = sqrt(max(psdFullOutput, 0));
psdFullInput = psdFullOutput * inputPerOutputScale^2;
asdFullInput = sqrt(max(psdFullInput, 0));
fullRecordDf = frequencyFull(2) - frequencyFull(1);

[~, index1Hz] = min(abs(frequency - 1));
frequencyAt1Hz = frequency(index1Hz);
outputAsd1HzUv = asdOutput(index1Hz) * 1e6;
outputPsd1Hz = psdOutput(index1Hz);
inputAsd1HzNv = asdInput(index1Hz) * 1e9;
inputPsd1Hz = psdInput(index1Hz);

bandName = ["0.1-1Hz"; "0.8-1.2Hz"; "1-10Hz"; "10-100Hz"; ...
    "100Hz-1kHz"; "1-10kHz"; "10-30kHz"; "30-50kHz"; ...
    "0.1Hz-30kHz"; "0.1Hz-50kHz"];
bandStart = [0.1; 0.8; 1; 10; 100; 1e3; 10e3; 30e3; 0.1; 0.1];
bandEnd = [1; 1.2; 10; 100; 1e3; 10e3; 30e3; 50e3; 30e3; 50e3];
bandSummaryTable = makeBandSummary(frequency, psdOutput, psdInput, ...
    bandName, bandStart, bandEnd, df, adc, dac);
oneHzMask = bandMask(frequency, 0.8, 1.2, df);
oneHzOutputUv = asdOutput(oneHzMask) * 1e6;
oneHzInputNv = asdInput(oneHzMask) * 1e9;

windowSensitivityTable = makeWindowSensitivity(outputZeroMean, fs, ...
    cfg.windowSensitivitySeconds, cfg.overlapRatio, inputPerOutputScale, adc, dac);
[segmentStabilityTable, segmentInputNv] = makeSegmentStability( ...
    outputZeroMean, fs, window, windowSamples, step, nfft, ...
    inputPerOutputScale, adc, dac);
topSpurTable = makeTopSpurs(frequencyFull, psdFullOutput, ...
    inputPerOutputScale, cfg.spurCount, cfg.spurMinimumFrequencyHz, ...
    nyquist, cfg.spurMinimumSeparationHz, adc, dac);

[sourceManifestTable, inputSha256Manifest] = buildSourceManifest(cfg);
if nyquist >= cfg.extendedAnalysisEndHz
    extendedBandCoverage = "满足";
else
    extendedBandCoverage = "不满足";
end
if inputAsd1HzNv <= cfg.asdLimitAt1HzUvPerSqrtHz * 1e3
    formalConclusion = "满足";
    comparisonOperator = "<=";
else
    formalConclusion = "不满足";
    comparisonOperator = ">";
end
conclusionReason = sprintf([ ...
    'Conditional on configured G=%g, %s input-equivalent ASD at %.9g Hz ' ...
    'is %.9g uV/sqrtHz %s %.9g uV/sqrtHz; DAC/Pico background retained.'], ...
    cfg.fpgaGain, adc, frequencyAt1Hz, inputAsd1HzNv / 1e3, ...
    comparisonOperator, cfg.asdLimitAt1HzUvPerSqrtHz);

oneHzSummaryTable = table(prefix, string(cfg.inputMat), n, fs, duration, ...
    nyquist, rawVectorCount, metadataLength, trailingSamplesExcluded, ...
    nonfiniteSamplesExcluded, outputMean, std(outputZeroMean), ...
    min(outputVoltage), max(outputVoltage), outlier8SigmaCount, ...
    outlier8SigmaPercent, kAdc, kDac, cfg.fpgaGain, inputPerOutputScale, ...
    adcReferencePlane, string(cfg.fpgaGainEvidence), ...
    cfg.welchWindowSeconds, windowSamples, overlapSamples, ...
    cfg.overlapRatio, nfft, df, segmentCount, fullRecordDf, ...
    frequencyAt1Hz, outputAsd1HzUv, outputPsd1Hz, ...
    inputAsd1HzNv, inputPsd1Hz, median(oneHzOutputUv), ...
    mean(oneHzOutputUv), max(oneHzOutputUv), median(oneHzInputNv), ...
    mean(oneHzInputNv), max(oneHzInputNv), min(segmentInputNv), ...
    median(segmentInputNv), max(segmentInputNv), 0, ...
    cfg.requirementBandEndHz, cfg.extendedAnalysisEndHz, ...
    cfg.asdLimitAt1HzUvPerSqrtHz, extendedBandCoverage, ...
    string(cfg.requirementTestCondition), formalConclusion, ...
    string(conclusionReason), ...
    "mean removed; periodic Hann; no DAC/Pico baseline subtraction", ...
    inputSha256Manifest);
oneHzSummaryTable.Properties.VariableNames = summaryVariableNames(adc, dac);

fullSpectrumTable = table(frequency, psdOutput, asdOutput, ...
    asdOutput * 1e6, psdInput, asdInput, asdInput * 1e9);
fullSpectrumTable.Properties.VariableNames = { ...
    'Frequency_Hz', sprintf('%s_Output_PSD_V2_per_Hz', dac), ...
    sprintf('%s_Output_ASD_V_per_sqrtHz', dac), ...
    sprintf('%s_Output_ASD_uV_per_sqrtHz', dac), ...
    sprintf('%s_InputEq_PSD_V2_per_Hz', adc), ...
    sprintf('%s_InputEq_ASD_V_per_sqrtHz', adc), ...
    sprintf('%s_InputEq_ASD_nV_per_sqrtHz', adc)};
lowMask = frequencyFull <= cfg.lowFrequencyExportEndHz;
lowFrequencyTable = table(frequencyFull(lowMask), psdFullOutput(lowMask), ...
    asdFullOutput(lowMask) * 1e6, psdFullInput(lowMask), ...
    asdFullInput(lowMask) * 1e9);
lowFrequencyTable.Properties.VariableNames = { ...
    'Frequency_Hz', sprintf('%s_Output_PSD_V2_per_Hz', dac), ...
    sprintf('%s_Output_ASD_uV_per_sqrtHz', dac), ...
    sprintf('%s_InputEq_PSD_V2_per_Hz', adc), ...
    sprintf('%s_InputEq_ASD_nV_per_sqrtHz', adc)};
analysisParametersTable = buildParameterTable(cfg, adcReferencePlane, ...
    kAdc, kDac, nfft, formalConclusion);

outputFiles = outputPaths(cfg, prefix, adc, dac);
writetable(oneHzSummaryTable, outputFiles.oneHzSummary, 'Encoding', 'UTF-8');
writetable(bandSummaryTable, outputFiles.bandSummary, 'Encoding', 'UTF-8');
writetable(fullSpectrumTable, outputFiles.fullSpectrum, 'Encoding', 'UTF-8');
writetable(lowFrequencyTable, outputFiles.lowFrequency, 'Encoding', 'UTF-8');
writetable(topSpurTable, outputFiles.topSpurs, 'Encoding', 'UTF-8');
writetable(windowSensitivityTable, outputFiles.windowSensitivity, 'Encoding', 'UTF-8');
writetable(segmentStabilityTable, outputFiles.segmentStability, 'Encoding', 'UTF-8');
writetable(analysisParametersTable, outputFiles.parameters, 'Encoding', 'UTF-8');
writetable(sourceManifestTable, outputFiles.sourceManifest, 'Encoding', 'UTF-8');

makeSpectrumFigure(frequency, asdOutput * 1e6, frequencyAt1Hz, ...
    outputAsd1HzUv, sprintf('%s output ASD', dac), ...
    sprintf('%s output ASD (uV/sqrt(Hz))', dac), ...
    outputFiles.outputAsdPlot, cfg, [0.05 0.35 0.75], NaN, '');
makeSpectrumFigure(frequency, psdOutput, frequencyAt1Hz, outputPsd1Hz, ...
    sprintf('%s output PSD', dac), sprintf('%s output PSD (V^2/Hz)', dac), ...
    outputFiles.outputPsdPlot, cfg, [0.10 0.55 0.35], NaN, '');
makeSpectrumFigure(frequency, asdInput * 1e9, frequencyAt1Hz, ...
    inputAsd1HzNv, sprintf('%s input-equivalent ASD', adc), ...
    sprintf('%s input-equivalent ASD (nV/sqrt(Hz))', adc), ...
    outputFiles.inputAsdPlot, cfg, [0.55 0.20 0.65], ...
    cfg.asdLimitAt1HzUvPerSqrtHz * 1e3, 'ASD limit');
makeSpectrumFigure(frequency, psdInput, frequencyAt1Hz, inputPsd1Hz, ...
    sprintf('%s input-equivalent PSD', adc), ...
    sprintf('%s input-equivalent PSD (V^2/Hz)', adc), ...
    outputFiles.inputPsdPlot, cfg, [0.80 0.30 0.10], ...
    (cfg.asdLimitAt1HzUvPerSqrtHz * 1e-6)^2, 'PSD limit');
makeStabilityFigure(windowSensitivityTable, segmentStabilityTable, ...
    outputFiles.stabilityPlot, cfg.plotDpi, adc, dac);
writeTextSummary(outputFiles.textSummary, cfg, oneHzSummaryTable, ...
    bandSummaryTable, adc, dac);

result = struct;
result.config = cfg;
result.sourceFiles = sourceManifestTable;
result.calibrationSource = struct('adcCsv', string(cfg.adcCalibrationCsv), ...
    'dacCsv', string(cfg.dacCalibrationCsv), 'adcSlopeVPerCode', kAdc, ...
    'dacSlopeVPerCode', kDac, 'adcReferencePlane', adcReferencePlane, ...
    'fpgaGain', cfg.fpgaGain, 'inputPerOutputScale', inputPerOutputScale);
result.spectrum = struct('frequencyHz', frequency, ...
    'outputPsdV2PerHz', psdOutput, 'outputAsdVPerSqrtHz', asdOutput, ...
    'inputEquivalentPsdV2PerHz', psdInput, ...
    'inputEquivalentAsdVPerSqrtHz', asdInput, ...
    'fullRecordFrequencyHz', frequencyFull, ...
    'fullRecordOutputPsdV2PerHz', psdFullOutput, ...
    'fullRecordInputEquivalentPsdV2PerHz', psdFullInput);
result.summaryTable = oneHzSummaryTable;
result.bandSummaryTable = bandSummaryTable;
result.windowSensitivityTable = windowSensitivityTable;
result.segmentStabilityTable = segmentStabilityTable;
result.topSpurTable = topSpurTable;
result.outputFiles = outputFiles;
save(outputFiles.mat, 'result', '-v7.3');
end

