segmentInputEqAsd1Hz_nV = NaN(segmentCount, 1);
for k = 1:segmentCount
    index = segmentStartSample(k):(segmentStartSample(k) + welchWindowSamples - 1);
    segment = voutZeroMean_V(index) - mean(voutZeroMean_V(index));
    [pSegment, fSegment] = periodogram(segment, welchWindow, ...
        welchNfft, fs_Hz, 'onesided');
    [~, iSegment] = min(abs(fSegment - 1));
    segmentOutputAsd1Hz_uV(k) = sqrt(pSegment(iSegment)) * 1e6;
    segmentInputEqAsd1Hz_nV(k) = sqrt(pSegment(iSegment)) ...
        * scaleX3GinPerJG2out * 1e9;
end
