    & isfinite(value) & value > 0;
loglog(frequency(mask), value(mask), 'Color', color, 'LineWidth', 0.9, ...
    'DisplayName', '10 s Hann Welch');
hold on;
plot(pointFrequency, pointValue, 'o', 'MarkerSize', 7, ...
    'MarkerFaceColor', [0.85 0.15 0.15], 'MarkerEdgeColor', 'w', ...
    'DisplayName', sprintf('1 Hz: %.6g', pointValue));
xline(1, '--', 'Color', [0.45 0.45 0.45], 'HandleVisibility', 'off');
xline(requirementEndHz, '--', 'Color', [0.35 0.35 0.35], ...
    'LineWidth', 1.1, 'DisplayName', '30 kHz requirement edge');
if isfinite(limitValue) && limitValue > 0
    yline(limitValue, '--r', 'LineWidth', 1.2, ...
        'DisplayName', limitLabel);
end
grid on;
box on;
xlabel('Frequency (Hz)');
ylabel(yLabelText);
title(titleText);
subtitle(subtitleText);
legend('Location', 'best');
xlim([0.1 plotEndHz]);
exportgraphics(fig, outputPath, 'Resolution', dpi, 'BackgroundColor', 'white');
close(fig);
end

