% s20_analyze_ad9245_x3g_jg2_g100_psd_asd
% AD9245 X3G -> FPGA (G=100 label) -> DA9726 JG2 -> PicoScope total-chain
% PSD/ASD analysis using measured X3G and JG2 Vpp-Codepp slopes.
%
% Evidence limits:
%   - The PicoScope MAT is a measured JG2 output-voltage record.
%   - X3G input-equivalent results use k_X3G/(100*k_JG2).
%   - G=100 is the recorded test-condition label, not an independently
%     verified active-bitstream transfer function.
%   - DAC/PicoScope background is retained; no PSD baseline subtraction.
%   - No same-run X3G screenshot accompanies the MAT. The A-vector voltage
%     unit is corroborated by an X2G screenshot from the same Pico export
%     workflow and is therefore explicitly carried as limited evidence.
%   - The X3G calibration reference plane is the signal-generator setting
%     parsed from filenames because termination/load was not recorded.

clear;
clc;

%% Paths and processing configuration
dataDir = 'G:\01_laser\202607_电2test\YCQD_AD_9245\9245_noise\X3G_JG2_G100';
inputMat = fullfile(dataDir, 'X3G_100KS_s_20S.mat');
sameFormatUnitReferencePng = fullfile(fileparts(dataDir), ...
    'X2G_JG3_G100', 'X2G_100KS_s.png');
requirementPng = ['C:\Users\Administrator\AppData\Local\Temp\' ...
    'codex-clipboard-fff70216-6222-4594-b4e6-4a02c227d96a.png'];
x3gCalibrationCsv = ['G:\01_laser\202607_电2test\YCQD_AD_9245\' ...
    '9245_scale\X3G\AD9245_X3G_scale_result\' ...
    'AD9245_X3G_scale_fit_summary.csv'];
jg2CalibrationCsv = ['G:\01_laser\202607_电2test\SZSD_DAC9726\' ...
    '20260707_dac_scale\JG2\dac_sine_scale_result\' ...
    'JG2_dac_vpp_code_vpp_scale_vpp_fit_summary_20260708_164451.csv'];
outputDir = fullfile(dataDir, 'AD9245_X3G_JG2_G100_PSD_ASD_result');
scriptVersion = '2026-07-17-r1';

fpgaGain = 100;
fpgaGainEvidence = 'test directory and condition label; active RTL transfer not independently verified';
requirementBandEnd_Hz = 30e3;
extendedAnalysisEnd_Hz = 50e3;
asdLimitAt1Hz_uV_per_sqrtHz = 10;
requirementTestCondition = 'ADC input DC-30 kHz; 30 kHz first-order LPF; CW';
welchWindow_s = 10;
overlapRatio = 0.5;
windowSensitivity_s = [2; 5; 10; 20];
lowFrequencyExportEnd_Hz = 100;
spurMinimumFrequency_Hz = 0.1;
spurMinimumSeparation_Hz = 1;
spurCount = 20;
plotDpi = 220;

bandName = ["0.1-1Hz"; "0.8-1.2Hz"; "1-10Hz"; "10-100Hz"; ...
    "100Hz-1kHz"; "1-10kHz"; "10-30kHz"; "30-50kHz"; ...
    "0.1Hz-30kHz"; "0.1Hz-50kHz"];
bandStart_Hz = [0.1; 0.8; 1; 10; 100; 1e3; 10e3; 30e3; 0.1; 0.1];
bandEnd_Hz = [1; 1.2; 10; 100; 1e3; 10e3; 30e3; 50e3; 30e3; 50e3];

requiredFiles = {inputMat, sameFormatUnitReferencePng, requirementPng, ...
    x3gCalibrationCsv, jg2CalibrationCsv};
for k = 1:numel(requiredFiles)
    if ~exist(requiredFiles{k}, 'file')
        error('Required source does not exist: %s', requiredFiles{k});
    end
end
if ~exist(outputDir, 'dir')
    mkdir(outputDir);
end
copyfile(requirementPng, fullfile(outputDir, 'ADC_noise_requirement_source.png'));

%% Resolve the reviewed calibration rows
x3gTable = readtable(x3gCalibrationCsv);
x3gMask = strcmp(string(x3gTable.fitName), 'primary_non_near_rail');
if nnz(x3gMask) ~= 1
    error('Expected exactly one primary X3G calibration row.');
end
kX3G_V_per_code = x3gTable.slopeVPerCode(x3gMask);
x3gReferencePlane = string(x3gTable.referencePlane(x3gMask));

jg2Table = readtable(jg2CalibrationCsv);
if height(jg2Table) ~= 1
    error('Expected exactly one JG2 fit-summary row.');
end
kJG2_V_per_code = jg2Table.slope_vpp_per_code(1);
if ~isfinite(kX3G_V_per_code) || ~isfinite(kJG2_V_per_code) ...
        || kX3G_V_per_code <= 0 || kJG2_V_per_code <= 0
    error('Invalid X3G/JG2 calibration slope.');
end
scaleX3GinPerJG2out = kX3G_V_per_code / (abs(fpgaGain) * kJG2_V_per_code);

%% Load and verify acquisition metadata
raw = load(inputMat);
if ~isfield(raw, 'A') || ~isfield(raw, 'Tinterval')
    error('MAT must contain A and Tinterval.');
end
rawVector = double(raw.A(:));
rawVectorCount = numel(rawVector);
if isfield(raw, 'Length') && isfinite(double(raw.Length(1)))
    metadataLength = double(raw.Length(1));
else
    metadataLength = rawVectorCount;
end
metadataLength = min(rawVectorCount, max(1, floor(metadataLength)));
trailingSampleCountExcluded = rawVectorCount - metadataLength;
vout_V = rawVector(1:metadataLength);
finiteMask = isfinite(vout_V);
nonfiniteSampleCountExcluded = nnz(~finiteMask);
vout_V = vout_V(finiteMask);

dt_s = double(raw.Tinterval(1));
if ~isfinite(dt_s) || dt_s <= 0
    error('Invalid Tinterval in source MAT.');
end
fs_Hz = 1 / dt_s;
sampleCount = numel(vout_V);
duration_s = sampleCount / fs_Hz;
nyquist_Hz = fs_Hz / 2;
if sampleCount < round(welchWindow_s * fs_Hz)
    error('Record is shorter than the configured Welch window.');
end

voutMean_V = mean(vout_V);
voutZeroMean_V = vout_V - voutMean_V;
vinEq_V = voutZeroMean_V * scaleX3GinPerJG2out;

rawMedian_V = median(vout_V);
rawMad_V = median(abs(vout_V - rawMedian_V));
robustSigma_V = 1.4826 * rawMad_V;
if robustSigma_V > 0
    outlier8SigmaCount = nnz(abs(vout_V - rawMedian_V) > 8 * robustSigma_V);
else
    outlier8SigmaCount = 0;
end
outlier8SigmaPercent = 100 * outlier8SigmaCount / sampleCount;

%% Formal Welch spectrum: 10 s periodic Hann, 50 percent overlap
welchWindowSamples = min(round(welchWindow_s * fs_Hz), sampleCount);
welchOverlapSamples = floor(welchWindowSamples * overlapRatio);
welchNfft = welchWindowSamples;
welchWindow = hann(welchWindowSamples, 'periodic');

[psdOutput_V2_per_Hz, frequency_Hz] = pwelch(voutZeroMean_V, ...
    welchWindow, welchOverlapSamples, welchNfft, fs_Hz, 'onesided');
asdOutput_V_per_sqrtHz = sqrt(max(psdOutput_V2_per_Hz, 0));
psdInputEq_V2_per_Hz = psdOutput_V2_per_Hz * scaleX3GinPerJG2out^2;
asdInputEq_V_per_sqrtHz = sqrt(max(psdInputEq_V2_per_Hz, 0));
frequencyResolution_Hz = frequency_Hz(2) - frequency_Hz(1);
welchStep = welchWindowSamples - welchOverlapSamples;
welchSegmentCount = 1 + floor((sampleCount - welchWindowSamples) / welchStep);

%% Full-record periodic-Hann periodogram for low-frequency and spur screening
fullWindow = hann(sampleCount, 'periodic');
[psdFullOutput_V2_per_Hz, frequencyFull_Hz] = periodogram( ...
    voutZeroMean_V, fullWindow, sampleCount, fs_Hz, 'onesided');
asdFullOutput_V_per_sqrtHz = sqrt(max(psdFullOutput_V2_per_Hz, 0));
psdFullInputEq_V2_per_Hz = psdFullOutput_V2_per_Hz * scaleX3GinPerJG2out^2;
asdFullInputEq_V_per_sqrtHz = sqrt(max(psdFullInputEq_V2_per_Hz, 0));
fullRecordResolution_Hz = frequencyFull_Hz(2) - frequencyFull_Hz(1);

%% Point and band statistics
[~, index1Hz] = min(abs(frequency_Hz - 1));
frequencyAt1Hz_Hz = frequency_Hz(index1Hz);
outputAsdAt1Hz_uV_per_sqrtHz = asdOutput_V_per_sqrtHz(index1Hz) * 1e6;
outputPsdAt1Hz_V2_per_Hz = psdOutput_V2_per_Hz(index1Hz);
inputEqAsdAt1Hz_nV_per_sqrtHz = asdInputEq_V_per_sqrtHz(index1Hz) * 1e9;
inputEqPsdAt1Hz_V2_per_Hz = psdInputEq_V2_per_Hz(index1Hz);

bandSummaryTable = makeBandSummary(frequency_Hz, ...
    psdOutput_V2_per_Hz, psdInputEq_V2_per_Hz, ...
    bandName, bandStart_Hz, bandEnd_Hz, frequencyResolution_Hz);

oneHzBandMask = bandMaskWithTolerance(frequency_Hz, 0.8, 1.2, ...
    frequencyResolution_Hz);
oneHzOutputAsd_uV = asdOutput_V_per_sqrtHz(oneHzBandMask) * 1e6;
oneHzInputAsd_nV = asdInputEq_V_per_sqrtHz(oneHzBandMask) * 1e9;

%% Window-length sensitivity
nSensitivity = numel(windowSensitivity_s);
sensitivityDf_Hz = NaN(nSensitivity, 1);
sensitivitySegmentCount = NaN(nSensitivity, 1);
sensitivityFrequencyAt1Hz_Hz = NaN(nSensitivity, 1);
sensitivityOutputAsd1Hz_uV = NaN(nSensitivity, 1);
sensitivityInputEqAsd1Hz_nV = NaN(nSensitivity, 1);
sensitivityInputEqBandMedian_nV = NaN(nSensitivity, 1);
sensitivityInputEqBandMax_nV = NaN(nSensitivity, 1);

for k = 1:nSensitivity
    nwin = min(round(windowSensitivity_s(k) * fs_Hz), sampleCount);
    if nwin < sampleCount
        noverlap = floor(nwin * overlapRatio);
    else
        noverlap = 0;
    end
    [pTmp, fTmp] = pwelch(voutZeroMean_V, hann(nwin, 'periodic'), ...
        noverlap, nwin, fs_Hz, 'onesided');
    aOutTmp = sqrt(max(pTmp, 0));
    aInTmp = aOutTmp * scaleX3GinPerJG2out;
    [~, iTmp] = min(abs(fTmp - 1));
    dfTmp = fTmp(2) - fTmp(1);
    mTmp = bandMaskWithTolerance(fTmp, 0.8, 1.2, dfTmp);
    stepTmp = nwin - noverlap;

    sensitivityDf_Hz(k) = dfTmp;
    sensitivitySegmentCount(k) = 1 + floor((sampleCount - nwin) / stepTmp);
    sensitivityFrequencyAt1Hz_Hz(k) = fTmp(iTmp);
    sensitivityOutputAsd1Hz_uV(k) = aOutTmp(iTmp) * 1e6;
    sensitivityInputEqAsd1Hz_nV(k) = aInTmp(iTmp) * 1e9;
    sensitivityInputEqBandMedian_nV(k) = median(aInTmp(mTmp)) * 1e9;
    sensitivityInputEqBandMax_nV(k) = max(aInTmp(mTmp)) * 1e9;
end

windowSensitivityTable = table(windowSensitivity_s, sensitivityDf_Hz, ...
    sensitivitySegmentCount, sensitivityFrequencyAt1Hz_Hz, ...
    sensitivityOutputAsd1Hz_uV, sensitivityInputEqAsd1Hz_nV, ...
    sensitivityInputEqBandMedian_nV, sensitivityInputEqBandMax_nV, ...
    'VariableNames', {'Window_s', 'Df_Hz', 'SegmentCount', ...
    'FrequencyAt1Hz_Hz', 'JG2_Output_ASD_1Hz_uV_per_sqrtHz', ...
