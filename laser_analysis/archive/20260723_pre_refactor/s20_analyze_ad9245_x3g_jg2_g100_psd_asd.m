%% Local functions
function mask = bandMaskWithTolerance(frequency, startHz, endHz, dfHz)
tolerance = max(abs(dfHz) * 1e-6, eps(max(abs(frequency))) * 10);
mask = frequency >= startHz - tolerance & frequency <= endHz + tolerance;
end

function tableOut = makeBandSummary(frequency, psdOutput, psdInput, ...
    bandName, bandStart, bandEnd, dfHz)
nBand = numel(bandName);
binCount = zeros(nBand, 1);
outputMedian_uV = NaN(nBand, 1);
outputMean_uV = NaN(nBand, 1);
outputP95_uV = NaN(nBand, 1);
outputMax_uV = NaN(nBand, 1);
outputMaxFrequency_Hz = NaN(nBand, 1);
outputIntegrated_uVrms = NaN(nBand, 1);
inputMedian_nV = NaN(nBand, 1);
inputMean_nV = NaN(nBand, 1);
inputP95_nV = NaN(nBand, 1);
inputMax_nV = NaN(nBand, 1);
inputMaxFrequency_Hz = NaN(nBand, 1);
inputIntegrated_uVrms = NaN(nBand, 1);

for k = 1:nBand
    mask = bandMaskWithTolerance(frequency, bandStart(k), bandEnd(k), dfHz);
    f = frequency(mask);
    pOut = psdOutput(mask);
    pIn = psdInput(mask);
    aOut = sqrt(max(pOut, 0)) * 1e6;
    aIn = sqrt(max(pIn, 0)) * 1e9;
    binCount(k) = numel(f);
    if isempty(f)
        continue;
    end
    [outputMax_uV(k), indexOut] = max(aOut);
    [inputMax_nV(k), indexIn] = max(aIn);
    outputMedian_uV(k) = median(aOut);
    outputMean_uV(k) = mean(aOut);
    outputP95_uV(k) = localPercentile(aOut, 95);
    outputMaxFrequency_Hz(k) = f(indexOut);
    inputMedian_nV(k) = median(aIn);
    inputMean_nV(k) = mean(aIn);
    inputP95_nV(k) = localPercentile(aIn, 95);
    inputMaxFrequency_Hz(k) = f(indexIn);
    if numel(f) > 1
        outputIntegrated_uVrms(k) = sqrt(trapz(f, pOut)) * 1e6;
        inputIntegrated_uVrms(k) = sqrt(trapz(f, pIn)) * 1e6;
    end
end

tableOut = table(bandName, bandStart, bandEnd, binCount, ...
    outputMedian_uV, outputMean_uV, outputP95_uV, outputMax_uV, ...
    outputMaxFrequency_Hz, outputIntegrated_uVrms, ...
    inputMedian_nV, inputMean_nV, inputP95_nV, inputMax_nV, ...
    inputMaxFrequency_Hz, inputIntegrated_uVrms, ...
    'VariableNames', {'Band', 'Start_Hz', 'End_Hz', 'BinCount', ...
    'JG2_Output_ASD_Median_uV_per_sqrtHz', ...
    'JG2_Output_ASD_Mean_uV_per_sqrtHz', ...
    'JG2_Output_ASD_P95_uV_per_sqrtHz', ...
    'JG2_Output_ASD_Max_uV_per_sqrtHz', ...
    'JG2_Output_ASD_Max_Frequency_Hz', ...
    'JG2_Output_IntegratedNoise_uVrms', ...
    'X3G_InputEq_ASD_Median_nV_per_sqrtHz', ...
    'X3G_InputEq_ASD_Mean_nV_per_sqrtHz', ...
    'X3G_InputEq_ASD_P95_nV_per_sqrtHz', ...
    'X3G_InputEq_ASD_Max_nV_per_sqrtHz', ...
    'X3G_InputEq_ASD_Max_Frequency_Hz', ...
    'X3G_InputEq_IntegratedNoise_uVrms'});
end

function value = localPercentile(data, percentile)
sorted = sort(double(data(:)));
if isempty(sorted)
    value = NaN;
    return;
end
position = 1 + (numel(sorted) - 1) * percentile / 100;
lowIndex = floor(position);
highIndex = ceil(position);
if lowIndex == highIndex
    value = sorted(lowIndex);
else
    fraction = position - lowIndex;
    value = sorted(lowIndex) * (1 - fraction) + sorted(highIndex) * fraction;
end
end

function tableOut = makeTopSpurTable(frequency, psdOutput, scale, ...
    count, minFrequency, maxFrequency, minSeparation)
candidateMask = frequency >= minFrequency & frequency <= maxFrequency ...
    & isfinite(psdOutput) & psdOutput > 0;
candidateIndex = find(candidateMask);
[~, order] = sort(psdOutput(candidateIndex), 'descend');
candidateIndex = candidateIndex(order);
selectedIndex = zeros(count, 1);
selectedCount = 0;
for k = 1:numel(candidateIndex)
    index = candidateIndex(k);
    if selectedCount == 0 || all(abs(frequency(index) ...
            - frequency(selectedIndex(1:selectedCount))) >= minSeparation)
        selectedCount = selectedCount + 1;
        selectedIndex(selectedCount) = index;
        if selectedCount == count
            break;
        end
    end
end
selectedIndex = selectedIndex(1:selectedCount);
rank = (1:selectedCount).';
frequency_Hz = frequency(selectedIndex);
JG2_Output_PSD_V2_per_Hz = psdOutput(selectedIndex);
JG2_Output_ASD_uV_per_sqrtHz = sqrt(JG2_Output_PSD_V2_per_Hz) * 1e6;
X3G_InputEq_PSD_V2_per_Hz = JG2_Output_PSD_V2_per_Hz * scale^2;
X3G_InputEq_ASD_nV_per_sqrtHz = sqrt(X3G_InputEq_PSD_V2_per_Hz) * 1e9;
tableOut = table(rank, frequency_Hz, JG2_Output_PSD_V2_per_Hz, ...
    JG2_Output_ASD_uV_per_sqrtHz, X3G_InputEq_PSD_V2_per_Hz, ...
    X3G_InputEq_ASD_nV_per_sqrtHz);
end

function makeSpectrumFigure(frequency, value, pointFrequency, pointValue, ...
    titleText, yLabelText, subtitleText, outputPath, plotEndHz, dpi, color, ...
    requirementEndHz, limitValue, limitLabel)
fig = figure('Visible', 'off', 'Color', 'w', 'Position', [100 100 1250 720]);
